export function getAgentById(id: string, namespace?: 'LE' | 'SP'): AgentDefinition | undefined {
  if (namespace) {
    return (namespace === 'LE' ? LE_AGENTS : SP_AGENTS).find((a) => a.id === id);
  }
  return ALL_AGENTS.find((a) => a.id === id);
}
